// Generate one Storybook file per component from dist/api/examples.json (the docs site's examples).
// Each component gets its markup as a static story (CSS only) and the live example page (with vimaksh.js).
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { root } from './config.mjs';
const ex = JSON.parse(readFileSync(root('dist/api/examples.json'), 'utf8'));
const comps = JSON.parse(readFileSync(root('dist/api/components.json'), 'utf8')).components;
rmSync(root('storybook/stories'), { recursive: true, force: true }); mkdirSync(root('storybook/stories'), { recursive: true });
let n = 0;
for (const c of comps) {
  const list = ex.filter(e => e.component === c.name); if (!list.length) continue;
  const files = list.map(e => e.file);
  const stories = list.map((e, i) => {
    const id = 'Example' + (i + 1);
    return `export const ${id} = { name: ${JSON.stringify(e.title + ' (markup)')}, render: () => ${JSON.stringify(`<div style="padding:28px var(--pad)">${e.html}</div>`)} };
export const ${id}Live = { name: ${JSON.stringify(e.title + ' (live, with vimaksh.js)')}, render: () => \`<iframe src="${files[i]}" style="display:block;width:100%;height:${Math.max(e.height || 400, 400)}px;border:0" title=${JSON.stringify(e.title)}></iframe>\` };`;
  }).join('\n');
  writeFileSync(root(`storybook/stories/${c.name}.stories.js`), `// Generated by scripts/stories.mjs from dist/api/examples.json. Do not edit.
export default { title: ${JSON.stringify(`${c.group}/${c.title}`)}, parameters: { docs: { description: { component: ${JSON.stringify(c.summary)} } } } };
${stories}
`);
  n++;
}
console.log(`stories: ${n} components`);
